"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";

interface Enrollment {
  readonly factorId: string;
  readonly qrCode: string;
  readonly secret: string;
}

export function MfaClient({ verifiedFactorId }: { readonly verifiedFactorId: string | null }) {
  const router = useRouter();
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  // No verified factor yet: start a TOTP enrollment (QR code + secret)
  useEffect(() => {
    if (verifiedFactorId) return;
    let cancelled = false;
    (async () => {
      const supabase = createClient();
      // Drop half-finished enrollments so a fresh one can be created
      const { data: factors } = await supabase.auth.mfa.listFactors();
      for (const f of factors?.all ?? []) {
        if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const { data, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: `DeployX ${new Date().toISOString().slice(0, 10)}`,
      });
      if (cancelled) return;
      if (enrollError || !data) {
        setError(enrollError?.message ?? "Could not start enrollment");
        return;
      }
      setEnrollment({ factorId: data.id, qrCode: data.totp.qr_code, secret: data.totp.secret });
    })();
    return () => {
      cancelled = true;
    };
  }, [verifiedFactorId]);

  const factorId = verifiedFactorId ?? enrollment?.factorId ?? null;

  const verify = async (event: React.FormEvent) => {
    event.preventDefault();
    if (!factorId) return;
    setBusy(true);
    setError(null);
    const { error: verifyError } = await createClient().auth.mfa.challengeAndVerify({
      factorId,
      code: code.trim(),
    });
    setBusy(false);
    if (verifyError) {
      setError(verifyError.message);
      return;
    }
    router.replace("/");
    router.refresh();
  };

  return (
    <form onSubmit={verify} className="space-y-4">
      {!verifiedFactorId && enrollment && (
        <div className="space-y-2 text-center">
          {/* qr_code is an SVG data URI generated by Supabase Auth */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={enrollment.qrCode} alt="Scan with your authenticator app" className="mx-auto w-44 h-44 bg-white rounded p-2" />
          <p className="text-[11px] text-on-surface-variant">
            Or enter this key: <span className="font-mono break-all text-on-surface">{enrollment.secret}</span>
          </p>
        </div>
      )}
      <label className="flex flex-col gap-1 text-xs text-on-surface-variant">
        6-digit code
        <input
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="[0-9]{6}"
          maxLength={6}
          required
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
          className="bg-surface-container-highest border border-outline-variant rounded px-3 py-2 text-center font-mono text-lg tracking-widest text-on-surface"
        />
      </label>
      {error && <p role="alert" className="text-xs text-error">{error}</p>}
      <button
        type="submit"
        disabled={busy || !factorId || code.length !== 6}
        className="w-full py-2 text-sm font-bold rounded bg-primary text-on-primary disabled:opacity-40"
      >
        {busy ? "Verifying…" : verifiedFactorId ? "Verify" : "Turn on two-factor"}
      </button>
    </form>
  );
}
